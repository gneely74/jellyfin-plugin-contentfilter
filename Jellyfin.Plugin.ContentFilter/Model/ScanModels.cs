using System.Text.Json.Serialization;

namespace Jellyfin.Plugin.ContentFilter.Models;

/// <summary>
/// Represents the state of a content scan.
/// </summary>
[JsonConverter(typeof(JsonStringEnumConverter))]
public enum ScanState
{
    /// <summary>
    /// No scan is running.
    /// </summary>
    Idle,

    /// <summary>
    /// A scan is in progress.
    /// </summary>
    Scanning,

    /// <summary>
    /// The scan completed successfully.
    /// </summary>
    Complete,

    /// <summary>
    /// The scan was cancelled.
    /// </summary>
    Cancelled,

    /// <summary>
    /// The scan failed.
    /// </summary>
    Error,
}

/// <summary>
/// Represents scan status for a media item.
/// </summary>
public sealed class ScanStatus
{
    /// <summary>
    /// Gets or sets the item identifier.
    /// </summary>
    public Guid ItemId { get; set; }

    /// <summary>
    /// Gets or sets the current scan state.
    /// </summary>
    public ScanState State { get; set; } = ScanState.Idle;

    /// <summary>
    /// Gets or sets the scan progress from 0.0 to 1.0.
    /// </summary>
    public double Progress { get; set; }

    /// <summary>
    /// Gets or sets the current time marker.
    /// </summary>
    public string CurrentTime { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the number of cues found.
    /// </summary>
    public int CuesFound { get; set; }

    /// <summary>
    /// Gets or sets the error message, when applicable.
    /// </summary>
    public string? Error { get; set; }

    /// <summary>
    /// Gets or sets the scan start timestamp.
    /// </summary>
    public DateTime? StartedAt { get; set; }

    /// <summary>
    /// Gets or sets the scan completion timestamp.
    /// </summary>
    public DateTime? CompletedAt { get; set; }
}

/// <summary>
/// Represents a queued scan request.
/// </summary>
public sealed class ScanJob
{
    /// <summary>
    /// Gets or sets the item identifier.
    /// </summary>
    public Guid ItemId { get; set; }

    /// <summary>
    /// Gets or sets the cancellation token source for the scan.
    /// </summary>
    public CancellationTokenSource Cts { get; init; } = new();
}

/// <summary>
/// Represents a cue DTO used by HTTP APIs.
/// </summary>
public sealed class CueDto
{
    /// <summary>
    /// Gets or sets the cue key.
    /// </summary>
    public string Key { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the cue start time string.
    /// </summary>
    public string Start { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the cue end time string.
    /// </summary>
    public string End { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets an optional description.
    /// </summary>
    public string? Description { get; set; }

    /// <summary>
    /// Gets or sets the cue category.
    /// </summary>
    public string Category { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the cue channel.
    /// </summary>
    public string Channel { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the cue action.
    /// </summary>
    public string Action { get; set; } = string.Empty;
}

/// <summary>
/// Persisted SQLite record tracking when a media item was last scanned by NudeNet.
/// </summary>
public sealed class ItemNudityScanRecord
{
    /// <summary>
    /// Gets or sets the media item identifier.
    /// </summary>
    public Guid ItemId { get; set; }

    /// <summary>
    /// Gets or sets the physical media file path at scan time.
    /// </summary>
    public string MediaPath { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the physical media file size in bytes at scan time.
    /// </summary>
    public long FileSize { get; set; }

    /// <summary>
    /// Gets or sets the physical file last-modified timestamp in UTC at scan time.
    /// </summary>
    public DateTime LastModifiedUtc { get; set; }

    /// <summary>
    /// Gets or sets the UTC timestamp when the NudeNet scan completed.
    /// </summary>
    public DateTime ScannedAt { get; set; }

    /// <summary>
    /// Gets or sets the frame extraction rate (FPS) used for the scan.
    /// </summary>
    public double Fps { get; set; }

    /// <summary>
    /// Gets or sets the confidence threshold used for the scan.
    /// </summary>
    public double Threshold { get; set; }

    /// <summary>
    /// Gets or sets the number of nudity cues generated by the scan.
    /// </summary>
    public int CueCount { get; set; }
}

/// <summary>
/// Represents the state of the library-wide NudeNet visual nudity scan job.
/// </summary>
[JsonConverter(typeof(JsonStringEnumConverter))]
public enum NudityScanState
{
    /// <summary>No nudity scan is running.</summary>
    Idle,

    /// <summary>A nudity scan is currently in progress.</summary>
    Running,

    /// <summary>The nudity scan completed successfully.</summary>
    Complete,

    /// <summary>The nudity scan was cancelled.</summary>
    Cancelled,

    /// <summary>The nudity scan encountered a fatal error.</summary>
    Error
}

/// <summary>
/// Tracks live progress, counters, and recent logs for the library-wide NudeNet scan job.
/// </summary>
public sealed class NudityScanStatus
{
    /// <summary>Gets or sets the current scan state.</summary>
    public NudityScanState State { get; set; } = NudityScanState.Idle;

    /// <summary>Gets a value indicating whether a scan is currently running.</summary>
    public bool IsRunning => State == NudityScanState.Running;

    /// <summary>Gets or sets the total number of library video items queued for evaluation.</summary>
    public int TotalItems { get; set; }

    /// <summary>Gets or sets the number of items evaluated so far.</summary>
    public int ProcessedItems { get; set; }

    /// <summary>Gets or sets the number of items actually scanned via ffmpeg + NudeNet.</summary>
    public int ItemsScanned { get; set; }

    /// <summary>Gets or sets the number of items skipped (already scanned and unchanged).</summary>
    public int ItemsSkipped { get; set; }

    /// <summary>Gets or sets the total number of nudity cues created across the run.</summary>
    public int CuesGenerated { get; set; }

    /// <summary>Gets or sets the number of item errors encountered during the run.</summary>
    public int ErrorCount { get; set; }

    /// <summary>Gets or sets the overall progress percentage (0.0 to 100.0).</summary>
    public double ProgressPercentage { get; set; }

    /// <summary>Gets or sets the display name of the item currently being scanned.</summary>
    public string CurrentItemName { get; set; } = string.Empty;

    /// <summary>Gets or sets the UTC start time of the active or most recent run.</summary>
    public DateTime? StartedAt { get; set; }

    /// <summary>Gets or sets the UTC completion time of the most recent run.</summary>
    public DateTime? CompletedAt { get; set; }

    /// <summary>Gets or sets the last error message if the run failed.</summary>
    public string? LastErrorMessage { get; set; }

    /// <summary>Gets or sets the UTC timestamp of the next scheduled daily NudeNet scan.</summary>
    public DateTime? NextScheduledRun { get; set; }

    /// <summary>Gets or sets the recent log lines for UI display.</summary>
    public List<string> RecentLogs { get; set; } = [];
}

/// <summary>
/// Result payload for a single-item NudeNet nudity scan request.
/// </summary>
public sealed class SingleNudityScanResult
{
    /// <summary>Gets or sets the media item identifier.</summary>
    public Guid ItemId { get; set; }

    /// <summary>Gets or sets whether the scan succeeded.</summary>
    public bool Success { get; set; }

    /// <summary>Gets or sets the number of nudity cues created.</summary>
    public int CuesCreated { get; set; }

    /// <summary>Gets or sets an optional status or error message.</summary>
    public string? Message { get; set; }
}

/// <summary>
/// Live progress snapshot for an active or recently finished single-item NudeNet nudity scan.
/// </summary>
public sealed class SingleNudityScanProgress
{
    /// <summary>Gets or sets the media item identifier.</summary>
    public Guid ItemId { get; set; }

    /// <summary>Gets or sets whether the scan is currently active.</summary>
    public bool IsScanning { get; set; }

    /// <summary>Gets or sets the current scan stage description.</summary>
    public string Stage { get; set; } = "Idle";

    /// <summary>Gets or sets the number of frames processed so far.</summary>
    public int ProcessedFrames { get; set; }

    /// <summary>Gets or sets the total number of extracted frames (0 while extracting).</summary>
    public int TotalFrames { get; set; }

    /// <summary>Gets or sets the completion percentage (0 to 100).</summary>
    public int Percent { get; set; }
}
